"""Rendered in a calendar other than the Gregorian one (Hijri, Thai): out of scope."""


def accepted() -> tuple[str, ...]:
    """The candidates that render, in scope: the formats of the ``letters`` suite."""
    return tuple(f for f in candidates() if f not in REFUSED and f not in OUT_OF_SCOPE)


def candidates() -> dict[str, str]:
    """The formats to check, by label."""
    forms = [
        form
        for letter in string.ascii_letters
        for form in (letter, letter * 2, f"0{letter}", f"yyyy {letter}")
    ]
    return {form: form for form in (*forms, *BUDDHIST_FORMS)}


